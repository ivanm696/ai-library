# ---------------------------------------------------------------- 4
story.append(h_section("4", "Механизм внимания (Attention)", LEVEL_ADVANCED, "Продвинутый"))
story.append(Paragraph(
    "Внимание решает обе проблемы RNN: вместо последовательной передачи состояния, каждый токен "
    "напрямую «смотрит» на все остальные токены одновременно и решает, какие из них наиболее важны "
    "для его понимания. Это делается через три проекции каждого токена: Query (запрос), "
    "Key (ключ) и Value (значение).", S["Body"]))
story.append(code_block(
    "Attention(Q, K, V) = softmax( (Q * K^T) / sqrt(d_k) ) * V"))
story.append(Paragraph(
    "Интуиция: Query токена — это «что я ищу», Key каждого токена — это «что я предлагаю», "
    "их скалярное произведение даёт оценку релевантности, softmax превращает оценки в веса "
    "(в сумме дающие 1), а взвешенная сумма Value даёт итоговое представление токена с учётом контекста.", S["Body"]))
story.append(Paragraph("Многоголовое внимание (Multi-Head Attention)", S["H3"]))
story.append(Paragraph(
    "На практике внимание вычисляется параллельно несколько раз («голов») с разными обученными "
    "проекциями — это позволяет модели одновременно отслеживать разные типы связей "
    "(например, грамматические и смысловые) в одном и том же тексте.", S["Body"]))


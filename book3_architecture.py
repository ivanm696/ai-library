story.append(h_section("2", "Прямой проход, функция потерь и обратное распространение", LEVEL_ADVANCED, "Продвинутый"))
story.append(Paragraph(
    "Обучение нейросети состоит из повторяющегося цикла из трёх шагов: прямой проход (forward pass) "
    "вычисляет предсказание сети; функция потерь (loss function) измеряет, насколько предсказание "
    "отличается от правильного ответа; обратное распространение ошибки (backpropagation) вычисляет, "
    "как изменить каждый вес, чтобы уменьшить эту ошибку.", S["Body"]))
story.append(code_block(
    "for epoch in range(num_epochs):\n"
    "    for batch in training_data:\n"
    "        predictions = model.forward(batch.inputs)\n"
    "        loss = loss_function(predictions, batch.targets)\n"
        "        loss.backward()                       # обратное распространение\n"
        "        optimizer.step()                     # обновление весов\n"
    "        optimizer.zero_grad()"))
story.append(Paragraph(
    "Обратное распространение использует правило цепочки (chain rule) из математического анализа, "
    "чтобы эффективно вычислить вклад каждого веса в итоговую ошибку, двигаясь от выходного слоя "
    "обратно к входному.", S["Body"]))


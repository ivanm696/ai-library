story.append(tools)
story.append(Spacer(1, 6 * mm))

# ---------------------------------------------------------------- 2
story.append(h_section("2", "Чат-интерфейс vs API: в чём разница", LEVEL_BEGINNER, "Начинающий"))
story.append(Paragraph(
    "Чат-интерфейс (сайт или приложение) — для разовых диалогов человека с моделью. "
    "API (Application Programming Interface) — способ, которым ваша собственная программа отправляет "
    "запросы модели и получает ответ автоматически, без участия человека на каждом шаге.", S["Body"]))
story.append(code_block(
    "# Пример вызова API (псевдокод, структура одинакова у большинства провайдеров)\n"
    "response = client.messages.create(\n"
    "    model=\"модель-id\",\n"
    "    max_tokens=1024,\n"
    "    messages=[\n"
    "        {\"role\": \"user\", \"content\": \"Объясни квадратичную формулу простыми словами\"}\n"
    "    ]\n"
    ")\n"
    "print(response.content)"))
story.append(note_block(
    "API обычно тарифицируется по числу «токенов» (кусочков текста, см. Книгу 3) на входе и выходе, "
    "а не по количеству запросов — длинный контекст стоит дороже."))

# ---------------------------------------------------------------- 3
story.append(h_section("3", "Что такое агент на практике", LEVEL_INTER, "Средний"))
story.append(Paragraph(
    "В отличие от обычного чат-ответа, агент выполняет цикл: получает задачу -> решает, какой "
    "инструмент вызвать (поиск, код, файл, другой API) -> выполняет вызов -> смотрит на результат -> "
    "решает, что делать дальше, повторяя цикл, пока задача не будет выполнена или не потребуется "
    "подтверждение человека.", S["Body"]))
story.append(code_block(
    "Цикл агента (упрощённо):\n"
    "while задача не завершена:\n"
    "    план = модель.решить_следующий_шаг(история, доступные_инструменты)\n"
    "    если план.нужен_инструмент:\n"
    "        результат = вызвать_инструмент(план.инструмент, план.аргументы)\n"
    "        история.добавить(результат)\n"
    "    иначе:\n"
    "        вернуть план.финальный_ответ"))
story.append(Paragraph(
    "Ключевой практический вопрос при проектировании агента — не «может ли модель это сделать», "
    "а «какие действия безопасно разрешить без подтверждения человека, а какие требуют паузы» "
    "(например: чтение файла — обычно безопасно; удаление или платёж — обычно требует подтверждения).", S["Body"]))

# ---------------------------------------------------------------- 4
story.append(h_section("4", "RAG: как модель отвечает по вашим документам", LEVEL_INTER, "Средний"))
story.append(Paragraph(
    "RAG (Retrieval-Augmented Generation, «генерация с подкреплением поиском») решает проблему: "
    "модель не знает содержимое ваших внутренних документов, потому что они не входили в её обучение. "
    "Вместо дообучения модели на ваших данных (дорого и негибко) в запрос перед генерацией ответа "
    "подмешивается релевантный фрагмент текста, найденный поиском.", S["Body"]))
story.append(code_block(
    "Шаги типичного RAG-пайплайна:\n"
    "1. Документы разбиваются на небольшие фрагменты (чанки)\n"
    "2. Каждый фрагмент превращается в embedding-вектор (см. Книгу 3) и сохраняется в векторной базе\n"
    "3. На вопрос пользователя находятся N наиболее похожих по смыслу фрагментов\n"
    "4. Эти фрагменты вставляются в промпт как контекст перед вопросом\n"
    "5. Модель отвечает, опираясь на предоставленный контекст, а не только на свои знания"))
story.append(note_block(
    "RAG снижает количество «выдуманных» фактов, но не устраняет их полностью — модель всё ещё может "
    "неверно интерпретировать найденный фрагмент. Качество RAG-системы сильно зависит от качества "
    "разбиения на чанки и точности поиска, а не только от самой языковой модели."))

# ---------------------------------------------------------------- 5
story.append(h_section("5", "Автоматизация рутинных задач", LEVEL_BEGINNER, "Начинающий"))
story.append(Paragraph(
    "Самые надёжные практические применения ИИ сегодня — не «заменить человека полностью», а снять "
    "рутину там, где цена ошибки невысока и результат легко проверить:", S["Body"]))
story.append(ListFlowable([
    ListItem(Paragraph("Черновики писем, описаний, постов — человек правит перед отправкой", S["Bullet"])),
    ListItem(Paragraph("Суммаризация длинных документов и встреч", S["Bullet"])),
    ListItem(Paragraph("Первичная сортировка обращений/заявок по категориям", S["Bullet"])),
    ListItem(Paragraph("Генерация шаблонного кода, тестов, документации по образцу", S["Bullet"])),
    ListItem(Paragraph("Перевод и адаптация текста под разные аудитории", S["Bullet"])),
], bulletType="bullet", start="•"))

# ---------------------------------------------------------------- 6
story.append(h_section("6", "Выбор между готовым инструментом и своей разработкой", LEVEL_INTER, "Средний"))
story.append(Paragraph(
    "Готовый инструмент (чат-интерфейс, no-code платформа) быстрее запустить, но даёт меньше контроля "
    "над поведением и данными. Своя разработка через API даёт полный контроль над промптами, доступом "
    "к инструментам и обработкой ошибок, но требует инженерных ресурсов на поддержку. Практическое правило: "
    "для разового или редкого использования — готовый инструмент; для встраивания в продукт или процесс, "
    "который должен работать стабильно и масштабироваться, — API.", S["Body"]))

# ---------------------------------------------------------------- 7
story.append(h_section("7", "Безопасная интеграция: ключи, права доступа, лимиты", LEVEL_ADVANCED, "Продвинутый"))
story.append(Paragraph(
    "При встраивании ИИ в реальный продукт или рабочий процесс важны те же базовые правила безопасности, "
    "что и для любого внешнего API:", S["Body"]))
story.append(ListFlowable([
    ListItem(Paragraph("Никогда не хранить API-ключи в коде, который попадает в публичный репозиторий", S["Bullet"])),
    ListItem(Paragraph("Давать агенту доступ только к тем инструментам и данным, которые реально нужны для задачи", S["Bullet"])),
    ListItem(Paragraph("Ставить лимиты (бюджет, число запросов) — агент может зациклиться и сгенерировать неожиданно много запросов", S["Bullet"])),
    ListItem(Paragraph("Логировать действия агента, особенно необратимые (запись в базу, отправка сообщений, платежи)", S["Bullet"])),
    ListItem(Paragraph("Использовать параметризованные SQL-запросы, избегать подстановки ввода в shell-команды и ограничивать разрешённые команды и аргументы; дополнительно проверять пользовательский ввод", S["Bullet"])),
], bulletType="bullet", start="•"))

# ---------------------------------------------------------------- 8
story.append(h_section("8", "Частые ошибки при внедрении ИИ в работу", LEVEL_INTER, "Средний"))
story.append(ListFlowable([
    ListItem(Paragraph("Доверие результату без проверки в задачах с высокой ценой ошибки (юридические, медицинские, финансовые тексты)", S["Bullet"])),
    ListItem(Paragraph("Отсутствие плана на случай сбоя модели или API (нет резервного сценария)", S["Bullet"])),
    ListItem(Paragraph("Передача в промпт чувствительных данных без понимания политики хранения данных у провайдера", S["Bullet"])),
    ListItem(Paragraph("Ожидание, что один и тот же промпт одинаково хорошо сработает на всех моделях", S["Bullet"])),
    ListItem(Paragraph("Автоматизация задачи целиком вместо постепенного внедрения с контролем на старте", S["Bullet"])),
], bulletType="bullet", start="•"))


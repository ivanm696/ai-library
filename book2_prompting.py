story.append(Paragraph("Негативные инструкции (negative prompting)", S["H3"]))
story.append(Paragraph(
    "Явное указание, чего делать НЕ нужно («не используй жаргон», «не придумывай источники, которых нет»), "
    "работает, но менее надёжно, чем позитивная формулировка желаемого поведения — по возможности "
    "формулируйте требования в положительном ключе.", S["Body"]))

